'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'../aetherwake.js'),'utf8');
const val=fs.readFileSync(path.join(__dirname,'../modules/save-payload-validator.js'),'utf8');
const save=src.slice(src.indexOf('function buildSavePayload()'),src.indexOf('function prepareSaveEnvelopeForApply('));
const snapshot=src.slice(src.indexOf('function captureLiveRuntimeForLoadRollback()'),src.indexOf('function restoreLiveRuntimeAfterFailedLoad('));
const restore=src.slice(src.indexOf('function restoreLiveRuntimeAfterFailedLoad('),src.indexOf('function applySaveEnvelope('));
const apply=src.slice(src.indexOf('function applySaveEnvelope('),src.indexOf('window._persistenceRuntime = Object.freeze'));
assert(save.includes('randomEncounterReview.getSteps()'));
assert(snapshot.includes('randomEncounterSteps: randomEncounterReview ? randomEncounterReview.getSteps() : null'));
assert(restore.includes('randomEncounterReview.restoreSteps(snapshot.runtime.randomEncounterSteps)'));
assert(apply.includes('randomEncounterReview.restoreSteps(payload.runtime.randomEncounterSteps ?? 0)'));
assert(apply.includes('randomEncounterPending = false'));
assert(val.includes('SAVE_RANDOM_ENCOUNTER_STEPS_RANGE')&&val.includes('SAVE_RANDOM_ENCOUNTER_STEPS_INVALID'));
const director=require('../modules/random-encounter-director.js');
const encounter=director.create();
for(let i=0;i<11;i++)encounter.onWalk(()=>0.99);
const saved=encounter.getSteps();
for(let i=0;i<9;i++)encounter.onWalk(()=>0.99);
encounter.restoreSteps(saved);
assert.equal(encounter.getSteps(),11);
assert.equal(encounter.onWalk(()=>0),true,'saved 11 steps should resume at next eligible step');
console.log('Optional random-encounter save, rollback, older-save reset contracts PASS');
